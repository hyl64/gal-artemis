// ---------------------------------------------------------------------------
// Rolling statistics, filled in by Mix() so tests can assert on what was
// actually produced instead of trusting it by ear.
// ---------------------------------------------------------------------------
struct RenderStats {
	int64_t framesRendered = 0;  // frames handed to the mixer
	int64_t peakFrames = 0;      // frames of source material consumed
	double sumSquares = 0.0;     // for RMS
	double peak = 0.0;           // max |sample|
	int64_t nonSilentFrames = 0; // frames containing any |sample| > kSilenceFloor
	double Reset();
};

// |sample| below this counts as silence when reporting "was it silent".
static constexpr float kSilenceFloor = 1.0f / 32768.0f;

// Mix bus ceiling.  Eight sound effects plus a BGM track at full volume
// overshoot 1.0, and clipping a summed mix produces the harshest artefact there
// is.  The bus therefore runs through a soft limiter: linear below kLimiterKnee
// so ordinary material is untouched, and asymptotic to 1.0 above it, so the
// output can never exceed full scale and never sits flat-topped at +/-1.
static constexpr float kLimiterKnee = 0.8f;
// The ceiling is deliberately below 1.0: tanh saturates to exactly 1.0f for
// large arguments, so limiting to 1.0 would still hand the device a full-scale
// sample.  Staying just under leaves headroom and keeps "never at full scale"
// true by construction.
static constexpr float kLimiterCeiling = 0.995f;
float SoftLimit(float sample);

// ---------------------------------------------------------------------------
// TrackInfo - what a container says about itself, without decoding audio.
// ---------------------------------------------------------------------------
struct TrackInfo {
	int sampleRate = 0;
	int channels = 0;
	int64_t frames = 0;    // per channel, from the container (matches afinfo)
	int64_t fileBytes = 0; // size on disk
	std::string codec;     // 'vorb' for Ogg Vorbis
	double Seconds() const {
		return sampleRate > 0 ? (double)frames / (double)sampleRate : 0.0;
	}
};

// ---------------------------------------------------------------------------
// Source - one seekable, streaming decode of a single .ogg.
//
// Audio is handed out as interleaved float32 in the file's *native* channel
// count and sample rate; no resampling happens here (see Stream for that).
// The file is never slurped into memory: ExtAudioFile pulls packets as asked,
// so memory use is independent of file size, which is what makes 3.4 MB BGM
// tracks (and 40 MB archives' worth of them) affordable.
// ---------------------------------------------------------------------------
class Source {
public:
	static std::unique_ptr<Source> Open(const std::string& path, std::string* error);

	~Source();
	Source(const Source&) = delete;
	Source& operator=(const Source&) = delete;

	const TrackInfo& Info() const { return info_; }

	// Reads up to `frames` frames into `out` (capacity frames*channels floats).
	// Returns frames actually decoded; 0 means end of file.
	int64_t Read(float* out, int64_t frames);

	// Absolute frame seek; returns false if the decoder refused.
	bool Seek(int64_t frame);

	int64_t Tell() const { return position_; }

private:
	Source() = default;
	struct Impl;
	std::unique_ptr<Impl> impl_;
	TrackInfo info_;
	int64_t position_ = 0;
};

// ---------------------------------------------------------------------------
// .sli - Sound Loop Information
// ---------------------------------------------------------------------------
enum class SliUnit {
	Unknown,
	Samples,
	Milliseconds,
};

struct SliLabel {
	int64_t position = 0;
	std::string name; // UTF-8
};

struct SliInfo {
	std::string version; // "2.00" for the "#2.00" header
	std::vector<SliLabel> labels;
	SliUnit unit = SliUnit::Unknown; // filled in by ResolveSliUnit()

	// Parses the text body.  Tolerates CRLF and arbitrary spacing between
	// fields, because the real writer pads with spaces and other WaveLoop
	// builds may pad differently.
	bool Parse(const std::string& utf8, std::string* error);

	// Parse from a file path (convenience).
	bool Load(const std::string& path, std::string* error);

	// Re-emits the exact byte layout described at the top of this file.
	// Used by the self-test as a round-trip assertion: parse(real bytes) then
	// Save() must reproduce the shipped file byte for byte.
	std::string Save() const;

	int64_t MaxPosition() const;
};

// Decides whether .sli positions are samples or milliseconds, using the file
// they describe as the yardstick rather than a guess.  Positions cannot exceed
// the clip they index, so any position past the clip's length in milliseconds
// rules milliseconds out.
SliUnit ResolveSliUnit(const SliInfo& sli, int64_t durationFrames, int sampleRate);

// Converts a .sli position to a frame offset given a resolved unit.
int64_t SliPositionToFrames(int64_t position, SliUnit unit, int sampleRate);

// ---------------------------------------------------------------------------
// LoopPlan - the A-B repeat window, in source frames.
//
//   [0, loopStart)   intro, played once
//   [loopStart, loopEnd)  repeated forever
//
// loopStart == 0 and loopEnd == frames means "loop the whole file", which is
// what a file with no .sli should do when the script asks for a looping BGM.
// ---------------------------------------------------------------------------
struct LoopPlan {
	int64_t introEnd = 0;  // == loopStart when there is no intro
	int64_t loopStart = 0;
	int64_t loopEnd = 0;
	int64_t frames = 0;
	bool looping = false;

	static LoopPlan Whole(int64_t frames);
	static LoopPlan FromSli(const SliInfo& sli, int64_t frames, int sampleRate);
	// Advances a source position across the windows; returns false when a
	// non-looping stream has run out.
	bool Advance(int64_t* position) const;
};

// ---------------------------------------------------------------------------
// Stream - one playing instance: a Source plus ring buffer, gain envelope,
// rate conversion and loop handling.  Cheap to create, but Open() does I/O so
// call it off the audio thread.
// ---------------------------------------------------------------------------
class Stream {
public:
	struct Config {
		int engineRate = 44100; // mixer output rate (44100 everywhere real data)
		int ringFrames = 16384; // ~0.37 s at 44100; must exceed Mix() tick size
		float volume = 1.0f;
	};

	static std::shared_ptr<Stream> Open(const std::string& path, const Config& cfg,
	                                    std::string* error);

	// Begins playback at the start of the plan.
	void Start(const LoopPlan& plan);

	// Decoder-thread side: top the ring up.  Returns frames of source written.
	int Fill();

	// Audio-thread side: adds this stream into `out` (interleaved stereo,
	// `frames` frames).  Applies gain/fade, consumes the ring.  Lock-free.
	void Mix(float* out, int frames);

	// Frames currently buffered and ready.
	int Buffered();
	// Non-looping stream that has delivered everything it ever will.
	bool Finished() const { return finished_.load(std::memory_order_acquire); }
	bool Looping() const { return plan_.looping; }

	// Fade: gain ramps to `target` over `ms`.  0 ms jumps immediately.
	void FadeTo(float target, int ms);
	// Ramp from an explicit starting gain.  Used for a fade-in from silence,
	// where the stream's current gain is whatever the previous track left behind.
	void FadeFromTo(float from, float to, int ms);
	// Hard stop at the next Mix() call (drops the ring).
	void Stop() { stopped_.store(true, std::memory_order_release); }
	bool Stopped() const { return stopped_.load(std::memory_order_acquire); }

	const TrackInfo& Info() const { return info_; }
	const LoopPlan& Plan() const { return plan_; }

private:
	Stream() = default;

	struct Impl;
	std::unique_ptr<Impl> impl_;
	TrackInfo info_;
	LoopPlan plan_;

	std::atomic<bool> finished_{false};
	std::atomic<bool> stopped_{false};

	// Fade requests cross from the control thread to the mixer without a lock:
	// the control thread publishes target and duration, then bumps fadeGen_;
	// the mixer latches a request when it sees the counter move.
	std::atomic<uint32_t> fadeGen_{0};
	std::atomic<float> fadeTarget_{1.0f};
	std::atomic<float> fadeFrom_{-1.0f}; // < 0 means "start from the current gain"
	std::atomic<int> fadeMs_{0};
};

// ---------------------------------------------------------------------------
// Engine - the interface `agame` talks to.
//
// One BGM channel, a fixed bank of sound-effect channels and one voice
// channel, which is the layout Artemis scripts assume ([bgm], [se], [voice]).
// A single decoder thread services every active stream, so adding sound
// effects does not add threads, and Mix() stays free of locks and I/O.
// ---------------------------------------------------------------------------
class Engine {
public:
	struct Config {
		std::string assetRoot; // directory holding *.ogg and *.ogg.sli
		int sampleRate = 44100;
		int seChannels = 8;
	};

	// Group volumes, mirroring the options a galgame exposes.
	enum Group { GroupBgm = 0, GroupSe = 1, GroupVoice = 2, GroupCount = 3 };

	Engine();
	~Engine();
	Engine(const Engine&) = delete;
	Engine& operator=(const Engine&) = delete;

	bool Open(const Config& cfg, std::string* error);
	void Shutdown();

	// [bgm file="moon"] with a .sli beside it: the intro plays once, then the
	// A-B window repeats.  fadeMs ramps the previous track out / this one in.
	bool PlayBgm(const std::string& name, bool loop, int fadeMs = 0);
	// Same, but with the .sli text supplied by the caller.  An archive keeps
	// `moon.ogg.sli` as a separate member, so a caller that already extracted
	// the member can hand the text straight in instead of writing it to disk.
	bool PlayBgmWithSli(const std::string& name, const std::string& sliText, bool loop,
	                    int fadeMs = 0);
	bool PlaySe(const std::string& name, int channel = -1);
	bool PlayVoice(const std::string& name);
	bool StopBgm(int fadeMs = 0);
	void StopAll();

	void SetVolume(Group group, float volume);
	float Volume(Group group) const;

	// Audio callback entry point.  `out` is interleaved float32 stereo,
	// `frames` frames.  No allocation, no locks, no file I/O.
	void Mix(float* out, int frames);

	// Frames mixed so far (monotonic), for tests and for the video clock.
	int64_t FramesMixed() const { return framesMixed_.load(std::memory_order_relaxed); }
	// How many streams are currently sounding (0 means the mixer is idle).
	int ActiveStreams() const;
	// Source frames decoded by the worker thread so far.
	int64_t FramesDecoded() const { return framesDecoded_.load(std::memory_order_relaxed); }
	// Frames buffered across every sounding stream.  A real audio callback is
	// paced by the device; a headless caller uses this to know the decoder has
	// caught up instead of draining the mixer instantly.
	int BufferedFrames() const;
	// Name of the BGM track that was last started, for logging.
	const std::string& CurrentBgm() const { return currentBgm_; }

private:
	struct Impl;
	std::unique_ptr<Impl> impl_;
	std::atomic<int64_t> framesMixed_{0};
	std::atomic<int64_t> framesDecoded_{0};
	std::atomic<float> volumes_[GroupCount];
	std::string currentBgm_;
};

