// audio.h - Ogg Vorbis decoding, Artemis `.sli` loop metadata, and a mixer
//
// This is the audio half of the port.  Two formats matter for a shipped
// Artemis title and both were read off real game data, not guessed:
//
//   *.ogg        Ogg Vorbis.  macOS decodes these natively through
//                CoreAudio's ExtAudioFile (AudioToolbox), which is the *same*
//                parser `afinfo` uses - so `afinfo` is an independent checker
//                for everything this file reports.  No third-party decoder is
//                needed and no Objective-C is involved: ExtAudioFile is a
//                plain C API, so this compiles as ordinary C++.
//
//                The real titles mix formats: BGM is 44100 Hz stereo while
//                sound effects are 44100 or 48000 Hz, mono or stereo
//                (`se/kisya.ogg` is 48000/2).  A mixer therefore has to do
//                rate conversion and mono->stereo itself; CoreAudio's client
//                format will not resample for us.
//
//   *.ogg.sli    "Sound Loop Information", a *separate text member* next to
//                the .ogg inside the archive (name = ogg name + ".sli"), not a
//                chunk inside the ogg.  A real one is 161..596 bytes:
//
//                  #2.00
//                  # Sound Loop Information (utf-8)
//                  # Generated by WaveLoopManager.cpp
//                  Label { Position=63488;            Name='ラベル0';                                }
//
//                Layout measured over 388 labels in 228 shipped files
//                (testdata/artemis-henpri-trial, HENPRI.pfs.060): every Label
//                line is exactly 86 bytes, the "Position=<number>;" block is
//                18 bytes wide (digit count plus space padding), the
//                "Name='...';" block is 18 bytes, and 32 spaces then put the
//                closing brace at column 85.  Padding is spaces, and names are
//                UTF-8 (katakana "ラベル0"), so the fixed widths are *byte*
//                widths, not character widths.
//
//                Position is a **sample offset**, not milliseconds.  The
//                evidence is in README/REALDATA notes and in
//                `audiotool sli`; briefly: across 224 real .sli/.ogg pairs
//                every Position is a multiple of 128 (388/388), and treating
//                Position as milliseconds puts the loop point 3.3x to 42.6x
//                past the end of the file it belongs to, while treating it as
//                samples lands inside every one of them (0.08..0.97 of the
//                clip).  noah5001.ogg is 558600 frames / 12.67 s and carries
//                Position=509952: 91% of the clip in samples, 8.5 minutes in
//                milliseconds - impossible for a 12-second line.
//
// Loop playback follows Artemis' "A-B repeat": the file plays from 0 to the
// loop point once (the intro), then repeats [loop point, end) forever.  With
// several Labels the loop point is the last one.
//
// One measured caveat shapes the loop code.  ExtAudioFileSeek on a Vorbis
// stream is *packet* aligned, not sample aligned: seeking to frame 441000 of a
// real BGM and reading gives audio whose first sample is source frame 441896
// (offset +896, and the samples themselves are then bit exact).  Seeking back to
// a loop point would therefore drop or repeat a fraction of a frame's worth of
// audio at every seam.  Stream avoids that: the first pass through the loop
// window is recorded, and later repeats play from that recording, so a loop is
// sample-exact and needs no seek at all.  Recording is only possible when no
// resampling is needed and the loop body is at most kMaxLoopCacheSeconds; a
// longer body falls back to seeking and its seam is packet aligned.
//
// Threading contract, which is what lets `agame` call this from a render loop
// without stalling: a decoder thread fills per-stream ring buffers, and Mix()
// only drains those rings.  Mix() allocates nothing, takes no locks and performs
// no I/O, so it is safe to call from a real audio callback.  Everything else may
// allocate but must not be called from the callback.

